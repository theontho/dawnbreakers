#!/usr/bin/env node
/**
 * Packs the naked-eye Hipparcos stars (magnitude 6.0 and brighter) into
 * `src/data/travelStars.ts` for the journey skies. Reads the checked-in
 * `data/sky/hipparcos.csv` (`npm run skyrewind:catalog` regenerates it).
 *
 *   node scripts/generate-travel-stars.mjs
 *
 * Each star is ten base-36 characters: right ascension (3, in 0.01 degrees),
 * declination (3, in 0.01 degrees from -90), magnitude (2, in 0.05 from -2)
 * and B-V colour index (2, in 0.02 from -0.5; `zz` when unknown). Positions
 * are the catalogue's J2000 frame; the game precesses them to each journey's
 * date. Proper motion is left out: over the 150 years back to the 1840s it
 * moves no naked-eye star more than a few arcminutes.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const MAGNITUDE_LIMIT = 6.0;
const ROW_WIDTH = 10;
const ROWS_PER_LINE = 120;
const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = path.join(REPO_ROOT, 'data', 'sky', 'hipparcos.csv');
const OUTPUT = path.join(REPO_ROOT, 'src', 'data', 'travelStars.ts');

const lines = readFileSync(SOURCE, 'utf8').split(/\r?\n/).filter(line => line && !line.startsWith('#'));
const header = lines.shift().split(',');
const column = name => {
  const index = header.indexOf(name);
  if (index < 0) throw new Error(`hipparcos.csv has no ${name} column`);
  return index;
};
const ra = column('raDeg');
const dec = column('decDeg');
const mag = column('mag');
const bv = column('bv');

const stars = lines
  .map(line => line.split(','))
  .map(cols => ({ ra: Number(cols[ra]), dec: Number(cols[dec]), mag: Number(cols[mag]), bv: cols[bv] === '' ? NaN : Number(cols[bv]) }))
  .filter(star => Number.isFinite(star.ra) && Number.isFinite(star.dec) && star.mag <= MAGNITUDE_LIMIT)
  // Brightest first, so a renderer can stop early for a faint-star cutoff.
  .sort((a, b) => a.mag - b.mag);

const pack = (value, width) => {
  const max = 36 ** width - 1;
  return Math.max(0, Math.min(max, Math.round(value))).toString(36).padStart(width, '0');
};
const packed = stars.map(star => [
  pack(((star.ra % 360) + 360) % 360 * 100, 3),
  pack((star.dec + 90) * 100, 3),
  pack((star.mag + 2) * 20, 2),
  Number.isFinite(star.bv) ? pack(Math.min(1294, (star.bv + 0.5) * 50), 2) : 'zz',
].join(''));

const chunks = [];
for (let i = 0; i < packed.length; i += ROWS_PER_LINE) chunks.push(`  '${packed.slice(i, i + ROWS_PER_LINE).join('')}',`);

writeFileSync(OUTPUT, `// Generated by scripts/generate-travel-stars.mjs from the Hipparcos catalogue. Do not edit.

/** ${stars.length} stars of magnitude ${MAGNITUDE_LIMIT.toFixed(1)} and brighter, brightest first, ${ROW_WIDTH} base-36 characters each. */
export const PACKED_TRAVEL_STARS = [
${chunks.join('\n')}
].join('');

export const PACKED_TRAVEL_STAR_WIDTH = ${ROW_WIDTH};
`);
console.log(`Wrote ${stars.length} stars to ${path.relative(REPO_ROOT, OUTPUT)}`);
