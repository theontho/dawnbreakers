#!/usr/bin/env node
/**
 * Writes docs/translation-glossary.md: the fixed renderings translators must
 * reuse, so a translation batch can match the game's terminology without
 * reading the (very large) locale catalogs.
 *
 *   npm run i18n:glossary
 *
 * Sections: style rules, curated core terms (below), every speaker name, and
 * every title and label, each with its current Farsi and Chinese rendering.
 * Regenerate after each translation batch.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { analyzeLocalization } from './lib/localization.mjs';

/** Terms that mostly appear inside sentences, so they have no catalog entry of their own. */
const CORE_TERMS = [
  ['the Báb', 'حضرت باب', '巴孛', 'Always honorific. fa: plural verbs and ایشان for Him; zh: 祂 for He/Him.'],
  ["Bahá'u'lláh", 'حضرت بهاءالله', '巴哈欧拉', 'Always honorific, as for the Báb.'],
  ['the Letters of the Living', 'حروف حی', '永生之字', ''],
  ['the Promised One', 'موعود', '应许者', ''],
  ["the Qá'im", 'قائم', '卡伊姆', ''],
  ['Siyyid Káẓim', 'سید کاظم', '赛义德·卡兹姆', ''],
  ['Mullá Ḥusayn', 'ملا حسین', '毛拉·侯赛因', ''],
  ['Quddús', 'قدّوس', '古杜斯', ''],
  ['Ṭáhirih', 'طاهره', '塔希丽', ''],
  ['Mubárak', 'مبارک', '穆巴拉克', ''],
  ['Karbilá', 'کربلا', '卡尔巴拉', ''],
  ['Shíráz', 'شیراز', '设拉子', ''],
  ['Shaykh Ṭabarsí', 'شیخ طبرسی', '谢赫·塔巴尔西', ''],
];

const STYLE_RULES = `## Style rules

- Never use an em-dash (—) in any language; rewrite with commas, colons or full stops.
- Quoted player choices: fa uses «...», zh uses “...”.
- Keep the two spaces before \`[E]\` in prompts (\`Enter the shrine  [E]\`), and keep leading arrows (\`↓ \`, \`→ \`).
- Keep \`{placeholders}\` exactly. Persian digits are applied automatically; write Latin digits in placeholders' surroundings as the source does.
- "Speak with X  [E]" prompts are built from a per-language template plus the **name** of X, so a new speaker only needs a name entry.
- Stage directions in parentheses stay in parentheses (fa ( ), zh （ ）).
- Tone: literary, warm, reverent; dramatised paraphrase of Nabíl, never modern slang.
- The Báb and Bahá'u'lláh are always referred to with honorifics (see Core terms).
`;

const analysis = analyzeLocalization();
const { root } = analysis;
const [fa, zh] = await Promise.all(['fa', 'zh'].map((l) => import(join(root, 'src', 'i18n', 'locales', `${l}.ts`))));

const cell = (s) => (s ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ');
const row = (en, f, z, note = '') => `| ${cell(en)} | ${cell(f)} | ${cell(z)} |${note ? ` ${cell(note)} |` : ''}`;

const names = [...analysis.namesRequired.keys()].sort((a, b) => a.localeCompare(b));
const shortFields = /\((title|label|subtitle|lockedLabel)\)$/;
const titles = [...analysis.translationRequired.entries()]
  .filter(([, refs]) => refs.some((r) => shortFields.test(r)))
  .map(([key]) => key)
  .sort((a, b) => a.localeCompare(b));

const out = `# Translation glossary

Generated by \`npm run i18n:glossary\` from the locale catalogs; do not edit by
hand (core terms live in \`scripts/i18n-glossary.mjs\`). Languages: English
(source), Farsi (fa, right-to-left), Chinese (zh, simplified).

${STYLE_RULES}
## Core terms

| English | fa | zh | Note |
| --- | --- | --- | --- |
${CORE_TERMS.map(([en, f, z, note]) => row(en, f, z, note || ' ')).join('\n')}

## Speaker names (${names.length})

| English | fa | zh |
| --- | --- | --- |
${names.map((n) => row(n, fa.names[n], zh.names[n])).join('\n')}

## Titles and labels (${titles.length})

| English | fa | zh |
| --- | --- | --- |
${titles.map((t) => row(t, fa.text[t], zh.text[t])).join('\n')}
`;

const file = join(root, 'docs', 'translation-glossary.md');
writeFileSync(file, out);
console.log(`${file}: ${CORE_TERMS.length} terms, ${names.length} names, ${titles.length} titles and labels`);
